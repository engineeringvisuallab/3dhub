#!/usr/bin/env node
// Validates the water treatment library (core/library/wtp) and prints the coverage ledger.
//   node tools/check-wtp.mjs          validate + print coverage
//   node tools/check-wtp.mjs --write  also regenerate docs/wtp/COVERAGE.md, CALCULATIONS.md and ASSESSMENTS.md
import { writeFileSync, mkdirSync } from 'node:fs';
import { loadWtp } from '../core/engine/wtp/node-loader.mjs';
import { buildRegistry, validate, coverage, STATUS_LEVELS } from '../core/engine/wtp/registry.js';

const data = loadWtp();
const reg = buildRegistry(data);
const errors = validate(reg);
const cov = coverage(reg);

console.log(`stages ${data.stages.length} | types ${cov.types} | stage calculations ${cov.stageCalcs} | assessments ${data.assessments.length} (${cov.assessmentCalcs} calculations) | rules ${cov.rules} | references ${data.refs.length}`);
console.log('type status:', STATUS_LEVELS.map(s => `${s} ${cov.byStatus[s]}`).join(', '));
for (const e of errors) console.log('ERROR ' + e);
console.log(errors.length ? `FAIL: ${errors.length} problem(s)` : 'OK: library is structurally sound');

if (process.argv.includes('--write')) {
  const out = new URL('../docs/wtp/', import.meta.url); mkdirSync(out, { recursive: true });
  const refName = id => reg.refs.get(id)?.title || id;
  let c = '# WTP coverage ledger\n\nGenerated by `node tools/check-wtp.mjs --write`. Do not edit by hand: edit `core/library/wtp/**` and regenerate.\n\n';
  c += `Status levels, in order: ${STATUS_LEVELS.join(' > ')}. A type is only "done" when it reaches **tested**.\n\n`;
  c += `Total: ${cov.types} types in ${data.stages.length} stages, ${cov.stageCalcs} stage calculations, ${data.assessments.length} assessments with ${cov.assessmentCalcs} calculations, ${cov.rules} expert rules.\n\n`;
  c += '| Stage | Model | Types | ' + STATUS_LEVELS.join(' | ') + ' | Calcs | Rules |\n|---|---|---|' + STATUS_LEVELS.map(() => '---').join('|') + '|---|---|\n';
  for (const r of cov.byStage) c += `| ${r.name} (\`${r.stage}\`) | ${r.model} | ${r.types} | ${STATUS_LEVELS.map(s => r.byStatus[s]).join(' | ')} | ${r.calcs} | ${r.rules} |\n`;
  c += '\n## Types by stage\n';
  for (const s of data.stages) {
    c += `\n### ${s.order}. ${s.name}\n\nModel: \`${s.model}\` | Folder: \`${s.modelPath}\` | References: ${s.refs.length ? s.refs.map(r => `${r.ref}${r.loc ? ' (' + r.loc + ')' : ''}`).join('; ') : '**none yet, a reference is needed**'}\n\n`;
    for (const g of s.groups) c += `- **${g.name}:** ${g.types.map(t => t.name + (t.status === 'listed' ? '' : ` [${t.status}]`)).join('; ')}\n`;
  }
  writeFileSync(new URL('COVERAGE.md', out), c);

  let k = '# WTP calculations per stage\n\nGenerated by `node tools/check-wtp.mjs --write`. Status `planned` means the calculation is named and its inputs and outputs fixed, but not yet implemented.\n';
  for (const s of data.stages) {
    k += `\n## ${s.order}. ${s.name}\n\n| Calculation | Inputs | Outputs | Status | Source |\n|---|---|---|---|---|\n`;
    for (const x of data.calcs[s.id]) k += `| ${x.name} (\`${x.id}\`) | ${x.inputs.join(', ')} | ${x.outputs.join(', ')} | ${x.status} | ${x.sources.length ? x.sources.map(y => y.ref + ' ' + y.loc).join('; ') : 'to be sourced'} |\n`;
  }
  writeFileSync(new URL('CALCULATIONS.md', out), k);

  let a = '# WTP assessments and their calculations\n\nGenerated by `node tools/check-wtp.mjs --write`. Each assessment is a separate module with its own calculations.\n';
  for (const x of data.assessments) {
    a += `\n## ${x.title}\n\nCategory: ${x.category}. ${x.purpose}\n\n| Calculation | Inputs | Outputs | Status |\n|---|---|---|---|\n`;
    for (const y of x.calculations) a += `| ${y.name} (\`${y.id}\`) | ${y.inputs.join(', ')} | ${y.outputs.join(', ')} | ${y.status} |\n`;
  }
  writeFileSync(new URL('ASSESSMENTS.md', out), a);
  let r = '# WTP references\n\nGenerated by `node tools/check-wtp.mjs --write`.\n\n| Id | Title | Pages | Text layer | Units |\n|---|---|---|---|---|\n';
  for (const x of data.refs) r += `| ${x.id} | ${x.title}${x.authors ? ', ' + x.authors : ''}${x.year ? ' (' + x.year + ')' : ''} | ${x.pages} | ${x.textLayer} | ${x.units} |\n`;
  writeFileSync(new URL('REFERENCES.md', out), r);
  console.log('wrote docs/wtp/COVERAGE.md, CALCULATIONS.md, ASSESSMENTS.md, REFERENCES.md');
}
process.exit(errors.length ? 1 : 0);
