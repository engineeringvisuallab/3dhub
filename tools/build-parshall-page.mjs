#!/usr/bin/env node
// Builds models/treatment-plant/rapid-mix/parametric/parshall-flume.html: the page template + the data + the engine, in one file.
//   node tools/build-parshall-page.mjs           write the page
//   node tools/build-parshall-page.mjs --check   exit 1 if the page on disk is stale
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const R = p => readFileSync(new URL('../' + p, import.meta.url), 'utf8');
export const PAGE = 'models/treatment-plant/rapid-mix/parametric/parshall-flume.html';
export function buildParshallPage() {
  const data = JSON.parse(R('core/library/wtp/data/parshall.json'));
  const strip = s => s.replace(/^export /gm, '');
  const engine = '// Generated by tools/build-parshall-page.mjs from core/engine/wtp/parshall.js, parshall-geometry.js and core/library/wtp/data/parshall.json. Do not edit here.\n'
    + 'const PF_DATA=' + JSON.stringify(data) + ';\n' + strip(R('core/engine/wtp/parshall.js')) + '\n' + strip(R('core/engine/wtp/parshall-geometry.js'));
  return R('tools/templates/parshall-flume.html').replace('/*@ENGINE*/', () => engine);
}
if (process.argv[1] && process.argv[1].endsWith('build-parshall-page.mjs')) {
  const out = buildParshallPage();
  if (process.argv.includes('--check')) { let cur = ''; try { cur = R(PAGE); } catch {} if (cur !== out) { console.log('STALE: run node tools/build-parshall-page.mjs'); process.exit(1); } console.log('page is up to date'); }
  else { mkdirSync(new URL('../models/treatment-plant/rapid-mix/parametric/', import.meta.url), { recursive: true }); writeFileSync(new URL('../' + PAGE, import.meta.url), out); console.log('wrote ' + PAGE + ' (' + out.length + ' bytes)'); }
}
